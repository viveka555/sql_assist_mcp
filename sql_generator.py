
"""
Generate SQL from natural-language questions using Groq.

The generated SQL is only a proposal. The existing MCP/database
layer must validate it before execution.
"""

import json
import logging
from typing import Any

from langchain_groq import ChatGroq
from langchain_core.messages import HumanMessage, SystemMessage

from config import get_settings


logger = logging.getLogger(__name__)


def _get_groq_api_key(settings: Any) -> str:
    """Return the Groq API key whether settings stores it as SecretStr or str."""

    api_key = settings.groq_api_key

    # Pydantic SecretStr protects secrets when displayed; extract the
    # underlying value only when passing it to the LLM client.
    if hasattr(api_key, "get_secret_value"):
        return api_key.get_secret_value()

    return str(api_key)


async def generate_sql(
    question: str,
    schema: dict[str, Any],
) -> str:
    """
    Ask Groq to generate one read-only SQL query for the supplied schema.

    Args:
        question: User's question in natural language.
        schema: Schema data returned by the MCP schema-inspection tool.

    Returns:
        SQL text generated by the model.

    Raises:
        ValueError: If the question is blank or the model returns no SQL.
    """

    if not question.strip():
        raise ValueError("Question cannot be empty.")

    settings = get_settings()

    # Use the configured Groq model and keep generation deterministic.
    llm = ChatGroq(
        model=settings.groq_model,
        api_key=_get_groq_api_key(settings),
        temperature=0,
    )

    # Supply only the schema needed to ground the model's SQL.
    schema_text = json.dumps(schema, indent=2)

    system_prompt = """
You are a careful PostgreSQL SQL generator.

Your task:
- Convert the user's question into one PostgreSQL SELECT query.
- Use only tables and columns present in the provided schema.
- Return SQL only: no explanation, Markdown, or code fences.
- Do not generate INSERT, UPDATE, DELETE, DROP, ALTER, CREATE,
  TRUNCATE, or any other write or DDL statement.
- Do not generate multiple statements.
- If the question cannot be answered from the schema, return:
  SELECT 'The requested information is not available in the schema'
  AS message
- Prefer explicit column names over SELECT * when practical.
- Do not assume columns or relationships that are not shown.
"""

    user_prompt = f"""
Database schema:
{schema_text}

User question:
{question}

Generate one PostgreSQL SELECT query.
"""

    response = await llm.ainvoke(
        [
            SystemMessage(content=system_prompt),
            HumanMessage(content=user_prompt),
        ]
    )

    generated_sql = str(response.content).strip()

    # Defensive cleanup in case the model ignores the SQL-only instruction.
    if generated_sql.startswith("```"):
        generated_sql = generated_sql.strip("`").strip()

        # Remove an optional language label such as "sql".
        if generated_sql.lower().startswith("sql"):
            generated_sql = generated_sql[3:].strip()

    if not generated_sql:
        logger.error("Groq returned an empty SQL response.")
        raise ValueError("The model did not generate SQL.")

    logger.info("Generated SQL from the user's question.")
    return generated_sql
